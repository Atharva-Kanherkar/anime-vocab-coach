/**
 * Original N5-aligned teaching content for the Your Lie in April track.
 *
 * Every Japanese string uses the source notation in ./text.ts and renders to romaji
 * or kana. Example sentences, dialogues and questions are original practice
 * material, not lines from the show. Recaps are short original summaries checked
 * against the official episode pages (yourlieinapril.com/story/NN.html). The
 * content is unreviewed: no Japanese educator has signed it off yet.
 *
 * In a choice question, the first choice is correct; the builder shuffles
 * choices deterministically.
 */
export type Skill = "vocabulary" | "grammar" | "reading" | "listening";
export interface ChoiceSource {
  id: string; skill: Skill; prompt: string; choices: string[]; explain: string;
  /** Japanese shown with the prompt (reading passages, "what does X mean?"). */
  ja?: string;
  /** Japanese played as audio; its transcript is revealed only in review. */
  audio?: string;
  /** Choices are English rather than Japanese. */
  en?: boolean;
  /** Objective override, e.g. a cumulative item reviewing an earlier unit. */
  objective?: string;
}
export interface WritingSource { id: string; prompt: string; references: string[]; objective?: string }
export interface UnitSource {
  unit: number;
  title: string;
  canDo: string;
  vocabulary: [src: string, meaning: string][];
  grammar: { title: string; explanation: string; examples: [src: string, english: string][] }[];
  dialogue: [speaker: "A" | "B", src: string, english: string][];
  questions: ChoiceSource[];
  writing: WritingSource[];
  speaking: { goal: string; opener: [src: string, english: string]; prompts: string[]; casual?: boolean };
  episode: { number: number; title: string; hook: string; summary: string } | null;
  kind: "episode" | "study" | "final";
}

const P = (id: string, skill: Skill, prompt: string, choices: string[], explain: string, extra: Partial<ChoiceSource> = {}): ChoiceSource =>
  ({ id, skill, prompt, choices, explain, ...extra });
const W = (id: string, prompt: string, references: string[], objective?: string): WritingSource => ({ id, prompt, references, ...(objective ? { objective } : {}) });

